"""Select only the interfaces supplied by the device's iPadOS kernel."""


def configure_drivers(core, board, edit):
    desktop = "#if defined(XNU_TARGET_OS_OSX) && XNU_TARGET_OS_OSX\n"
    # The iPadOS series has the common block hash accounting, but not the
    # optional per-core SHA timing counters used by this single diagnostic row.
    edit(board / "package/BootLog.c", [
        ("  // The digests alone (cssha-digest-time.patch):", desktop + "  // The digests alone (cssha-digest-time.patch):"),
        ("  if (log_display_on && &native_legacy_swap_rejected_count", "#endif\n  if (log_display_on && &native_legacy_swap_rejected_count"),
    ])
    probes = board / "package/LegacyDisplayProbe.cpp"
    for probe in ("sheng_ethernet_probe", "sheng_software_aes_probe"):
        call = f"    if ({probe}) {probe}();"
        edit(probes, [(call, desktop + call + "\n#endif")])
    # Export the offsets generated by the board's selected display ABI. The
    # diagnostic consumer and the real validator then use the same 24A446 layout.
    display = core / "drivers/GopFramebuffer/NativeLegacyDisplay.cpp"
    export = ('extern "C" const unsigned native_legacy_request_layout[6]='
              '{kRequestRect0,kRequestRect1,kRequestMasks,kRequestOptions,kRequestDims,kRequestSurfaces};')
    edit(display, [("#endif\nclass NativeLegacyDisplay;",
                    "#endif\n#if !defined(NATIVE_LEGACY_MACOS) || !NATIVE_LEGACY_MACOS\n" + export +
                    "\n#endif\nclass NativeLegacyDisplay;")])
    # Match the existing no-pager-notification path. Never report a GPU grant
    # as tracked when the kernel cannot notify the driver that all views closed.
    gpu = core / "drivers/Adreno740/NativeAdrenoPublish.cpp"
    edit(gpu, [("        const bool hook=&iokit_physical_descriptor_close_notify!=nullptr;",
                desktop + "        const bool hook=&iokit_physical_descriptor_close_notify!=nullptr;"),
               ("        NativeAdrenoPoolNoteView(grant,view->tracked_);",
                "#else\n        native_adreno_pool_views[4]=0;\n#endif\n"
                "        NativeAdrenoPoolNoteView(grant,view->tracked_);")])
    # This profile does not supply the optional operation for releasing loader
    # pages. Keep the packed seed reservation and the normal verified copy path.
    edit(core / "drivers/RamBlock/NativeRamBlock.cpp", [
        ("  uint32_t release = 0;", desktop + "  uint32_t release = 0;"),
        ("  memcpy(native_ram_block_seed_sha256,seedHash,32);", "#endif\n  memcpy(native_ram_block_seed_sha256,seedHash,32);"),
    ])
